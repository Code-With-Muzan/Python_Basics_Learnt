# String Fuction 

name = "Muzamil is an editor"

print(len(name)) # len function tells the length of the string
print(name.endswith("mila")) # endsswith function tells us about does the following strings, ends with the particular character or not
print(name.startswith("Muz")) # startswith function tells us about does the following strings, starts with the particular character or not
print(name.capitalize()) # capitalize function capitalizes the letter only in the start . Rest of the character will remain the same in the string 
print(name.upper()) # upper function uppercase the whole string 
print(name.lower()) # lower function lowercase the whole string 
print(name.find("is")) # find function helps us to find the word in a string and returns the index of first character if it finds the word 
print(name.replace("editor","EDITOR")) # replace function replaces a word from the string  

