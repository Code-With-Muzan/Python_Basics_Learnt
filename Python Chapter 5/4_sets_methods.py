s = {1,234,45,76,8,5,5,5,5}
s.add(476) # This function adds a new value in a set 
print(s)
len(s) # This function tells the length of set 
print(s)
s.remove(5) # This function removes a value/element from the set 
print(s)
s.pop() # This function will randomly remove a value/element from the set 
print(s)
s.clear() # This function clears the whole set 
print(s)